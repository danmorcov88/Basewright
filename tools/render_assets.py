def escape(text: str) -> str:
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


def svg(width: int, height: int, body: Iterable[str]) -> str:
    """Wrap rendered elements in a document, with the arrowhead every diagram uses."""
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img">',
        GENERATED_BY,
        "<defs>",
        '<marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" '
        'markerHeight="6" orient="auto">',
        '<path d="M 0 0 L 10 5 L 0 10 z" fill="context-stroke"/>',
        "</marker>",
        "</defs>",
        *body,
        "</svg>",
    ]
    return "\n".join(parts) + "\n"


def rect(
    x: float,
    y: float,
    w: float,
    h: float,
    *,
    fill: str,
    stroke: str = "none",
    radius: float = 6,
    width: float = 1,
    dash: str | None = None,
) -> str:
    dash_attr = f' stroke-dasharray="{dash}"' if dash else ""
    return (
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" '
        f'stroke="{stroke}" stroke-width="{width}"{dash_attr}/>'
    )


def text(
    x: float,
    y: float,
    content: str,
    *,
    fill: str,
    size: float = 13,
    family: str = SANS,
    weight: str = "normal",
    anchor: str = "start",
    spacing: str = "normal",
) -> str:
    return (
        f'<text x="{x}" y="{y}" fill="{fill}" font-family="{family}" font-size="{size}" '
        f'font-weight="{weight}" text-anchor="{anchor}" letter-spacing="{spacing}" '
        f'xml:space="preserve">{escape(content)}</text>'
    )


def line(x1: float, y1: float, x2: float, y2: float, *, stroke: str, arrow: bool = False) -> str:
    marker = ' marker-end="url(#arrow)"' if arrow else ""
    return (
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" '
        f'stroke-width="1.5"{marker}/>'
    )


