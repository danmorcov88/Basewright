def run(entry: Capture) -> list[str]:
    """Run a capture's command and keep what it printed, prompt line included."""
    result = subprocess.run(
        [sys.executable, "-m", *entry.command],
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=False,
    )
    printed = (result.stdout + result.stderr).replace("\r\n", "\n").rstrip("\n")
    lines = [f"$ {entry.prompt}"]
    lines.extend(printed.split("\n") if printed else [])
    return [line_text.rstrip() for line_text in lines]


def build() -> dict[Path, str]:
    """Render every asset. Keys are paths relative to the repository root."""
    assets: dict[Path, str] = {}
    printed = {entry.name: run(entry) for entry in CAPTURES}

    for theme in THEMES:
        suffix = theme.name
        assets[ASSETS / f"pipeline-{suffix}.svg"] = render_pipeline(theme)
        assets[ASSETS / f"decides-acts-{suffix}.svg"] = render_decides_acts(theme)
        assets[ASSETS / f"finished-vs-fit-{suffix}.svg"] = render_finished_vs_fit(theme)
        assets[ASSETS / f"decisions-{suffix}.svg"] = render_decisions(theme)
        assets[ASSETS / f"profile-anatomy-{suffix}.svg"] = render_profile_anatomy(theme)
        assets[ASSETS / f"facts-model-{suffix}.svg"] = render_facts_model(theme)
        assets[ASSETS / f"plan-anatomy-{suffix}.svg"] = render_plan_anatomy(theme)
        assets[ASSETS / f"sizing-journey-{suffix}.svg"] = render_sizing_journey(theme)
        assets[ASSETS / f"exit-codes-{suffix}.svg"] = render_exit_codes(theme)
        assets[ASSETS / f"verb-pipeline-{suffix}.svg"] = render_verb_pipeline(theme)
        assets[ASSETS / f"reachability-{suffix}.svg"] = render_reachability(theme)
        for entry in CAPTURES:
            assets[ASSETS / f"{entry.name}-{suffix}.svg"] = render_terminal(
                entry.title, printed[entry.name], theme
            )

    return assets


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="render_assets",
        description="Regenerate the documentation diagrams and terminal captures.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; fail if what is committed differs from what would be produced.",
    )
    args = parser.parse_args(argv)

    assets = build()
    ASSETS.mkdir(parents=True, exist_ok=True)

    if args.check:
        stale = [
            path
            for path, content in assets.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        # An image nothing renders any more is worse than a stale one: it stays committed,
        # keeps being referenced, and agrees with whatever the documentation says about it
        # for ever. The golden check has caught these from the start; this one did not,
        # until a capture was renamed and its old pair sat in the directory unnoticed.
        orphans = [path for path in sorted(ASSETS.glob("*.svg")) if path not in assets]

        for path in sorted(stale):
            print(f"stale: {path.relative_to(ROOT).as_posix()}", file=sys.stderr)
        for path in orphans:
            name = path.relative_to(ROOT).as_posix()
            print(f"not produced by any renderer: {name}", file=sys.stderr)
        if stale or orphans:
            print(
                "\nRun: python tools/render_assets.py, and delete what it no longer writes.",
                file=sys.stderr,
            )
            return 1
        print(f"{len(assets)} assets are current.")
        return 0

    for path, content in sorted(assets.items()):
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {len(assets)} assets to {ASSETS.relative_to(ROOT).as_posix()}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
