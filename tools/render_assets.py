#: Highlighting rules applied to captured output, in order. The first match on a line
#: wins. These describe the report vocabulary, not any one engine.
HIGHLIGHTS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"^\s*\$ "), "accent"),
    (re.compile(r"\bBLOCK\b|\bREFUSED\b|\bFAIL(ED)?\b"), "block"),
    (re.compile(r"\bWARN(ING)?\b|^\s*~ "), "warn"),
    (re.compile(r"\bPASS\b|\bOK\b|^\s*\+ "), "ok"),
    (re.compile(r"^[A-Z][A-Z ]{2,}$"), "accent"),
    (re.compile(r"^\s*#"), "muted"),
)


def _colour_for(line_text: str, theme: Theme) -> str:
    for pattern, attribute in HIGHLIGHTS:
        if pattern.search(line_text):
            return str(getattr(theme, attribute))
    return theme.fg


def render_terminal(title: str, lines: Sequence[str], theme: Theme) -> str:
    """Draw captured console output as a terminal window."""
    size = 12.5
    leading = 18
    pad = 18
    chrome = 34

    columns = max((len(line_text) for line_text in lines), default=0)
    width = int(pad * 2 + max(columns, len(title) + 12) * size * CHAR_WIDTH) + 8
    height = int(chrome + pad + max(len(lines), 1) * leading + pad)

    body: list[str] = [
        rect(0, 0, width, height, fill=theme.panel, stroke=theme.line, radius=8),
        rect(0, 0, width, chrome, fill=theme.bg, stroke="none", radius=8),
        f'<rect x="0" y="{chrome - 8}" width="{width}" height="8" fill="{theme.bg}"/>',
        line(0, chrome, width, chrome, stroke=theme.line),
    ]
    for index, colour in enumerate((theme.block, theme.warn, theme.ok)):
        body.append(f'<circle cx="{18 + index * 16}" cy="{chrome / 2}" r="5" fill="{colour}"/>')
    body.append(
        text(
            width / 2,
            chrome / 2 + 4,
            title,
            fill=theme.muted,
            size=12,
            family=SANS,
            anchor="middle",
        )
    )

    baseline = chrome + pad + leading - 5
    for index, line_text in enumerate(lines):
        body.append(
            text(
                pad,
                baseline + index * leading,
                line_text,
                fill=_colour_for(line_text, theme),
                size=size,
                family=MONO,
            )
        )
    return svg(width, height, body)


